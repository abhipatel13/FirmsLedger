const _BASE = (BASE_URL || 'https://www.firmsledger.com').replace(/\/$/, '');

const VALID_CATEGORIES = new Set(CATEGORY_SLUGS);
const VALID_STATES = new Set(ALL_US_STATES.map((s) => s.slug));

// Generated by scripts/build-static-data.mjs — every (category, subcategory,
// state) triple that has at least one approved company. Validating slugs was
// never the problem; validating INVENTORY is. Without this, the ~2,700 valid
// -but-empty triples each cost two aggregate queries to discover they were
// empty, and crawlers walking them kept the Neon compute from ever hitting its
// fixed 300s autosuspend. See HISTORY.md 2026-09-11.
const COMBO_KEYS = new Set(
  SUBCATEGORY_COMBOS.map((c) => `${c.category}|${c.sub}|${c.state}`)
);
// Prerender only what has real inventory. Matches MIN_LIVE_COMPANIES in
// app/sitemap.js, which already filters these URLs out of the sitemap below 5.
const PRERENDER_MIN = 5;

/**
 * True when this triple has no approved companies at all.
 *
 * Such a page used to render the PARENT category's companies via a count===0
 * fallback — a subcategory heading over unrelated listings, which is why the
 * sitemap already excluded them. We now redirect to the parent category+state
 * page instead: same content, honest URL, and zero queries to decide.
 *
 * NOT a 404: 29 of these URLs were earning Google impressions as of 2026-09-11
 * (235 impressions, three of them on page one), so 404ing them would throw away
 * real rankings. The redirect is temporary, not permanent, because a
 * subcategory can gain inventory later and get its page back.
 *
 * Falls open if the generated list is somehow empty — degrading to the old
 * query path beats redirecting the entire subcategory surface.
 */
function hasNoInventory(category, subcategory, state) {
  if (COMBO_KEYS.size === 0) return false;
  return !COMBO_KEYS.has(`${category}|${subcategory}|${state}`);
}

function toTitleCase(slug) {
  return slug.split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}

// ─── Metadata ─────────────────────────────────────────────────────────────────

export async function generateMetadata({ params }) {
  const { category, state: subcategory, subcategory: state } = await params;
  // Page 1, unfiltered — reading searchParams would force the route dynamic.
  const sParams = {};

  if (
    VALID_STATES.has(category) &&
    VALID_CATEGORIES.has(subcategory) &&
    CATEGORY_MAP[subcategory]?.subcategories.some((s) => s.slug === state)
  ) {
    const query = new URLSearchParams(sParams).toString();
    const target = query ? `/${subcategory}/${state}/${category}?${query}` : `/${subcategory}/${state}/${category}`;
    permanentRedirect(target);
  }

  const cat = CATEGORY_MAP[category];
  if (!cat) return { title: 'Not Found' };

  if (state && !VALID_STATES.has(state)) return { title: 'Not Found' };

  const sub = cat.subcategories.find((s) => s.slug === subcategory);
  const subName  = sub?.name || toTitleCase(subcategory);
  const stateName = toTitleCase(state);

  // The page component redirects this case to /{category}/{state}. Return
  // placeholder metadata with zero queries rather than paying for a count we
  // are about to discard — this is half the saving.
  if (hasNoInventory(category, subcategory, state)) {
    return { title: subName, robots: { index: false, follow: true } };
  }

  // The count===0 parent-category retry that used to live here is gone: anything
  // reaching this line has at least one company in the subcategory itself, so
  // the fallback was unreachable and only doubled the cost of empty pages.
  const count = await countCompaniesByCategoryAndState(subcategory, state);
  const categoryToUse = subcategory;

  // Some subcategory slugs (e.g. wiring-harness) live under more than one parent category —
  // disambiguate the title with the parent name so the two URLs don't produce identical <title>s.
  const parentsWithSub = MANUFACTURING_CATEGORIES.filter((c) => c.subcategories.some((s) => s.slug === subcategory));
  const parentShortName = parentsWithSub.length > 1 ? (cat.shortName || cat.name) : null;

  const subNoun = sub?.titleNoun || producerNoun(subName);

  const title = buildListingTitle({ count, noun: subNoun, stateName, parentShortName });
  const description = `Find ${subName.toLowerCase()} manufacturers in ${stateName}. Part of the ${cat.name} directory. No paid placements.`;
  const canonical = `${_BASE}/${category}/${subcategory}/${state}`;
  const { seo } = await stateListingSeo({ path: `/${category}/${subcategory}/${state}`, listSlug: subcategory, stateSlug: state, stateName, cat });
  const metaTitle = seo?.title || title;
  const metaDescription = seo?.description || description;

  return {
    title: metaTitle,
    description: metaDescription,
    alternates: { canonical },
    robots: count < 5 ? { index: false, follow: true } : { index: true, follow: true },
    openGraph: { images: OG_IMAGES, title: metaTitle, description: metaDescription, type: 'website', url: canonical },
  };
}

export function generateStaticParams() {
  // CAREFUL: the folder names do not match the URL. The [state] segment
  // carries the SUBCATEGORY slug and [subcategory] carries the STATE slug —
  // see the destructuring in generateMetadata and the page component. Swapping
  // these silently generates thousands of wrong pages.
  return SUBCATEGORY_COMBOS
    .filter((c) => c.n >= PRERENDER_MIN)
    .map((c) => ({ category: c.category, state: c.sub, subcategory: c.state }));
}



// ─── Page ─────────────────────────────────────────────────────────────────────

export default async function SubcategoryStatePage({ params }) {
  const { category, state: subcategory, subcategory: state } = await params;

  if (
    VALID_STATES.has(category) &&
    VALID_CATEGORIES.has(subcategory) &&
    CATEGORY_MAP[subcategory]?.subcategories.some((s) => s.slug === state)
  ) {
    permanentRedirect(`/${subcategory}/${state}/${category}`);
  }

  const activeEmployeeRanges = [];

  const cat = CATEGORY_MAP[category];
  if (!cat || !VALID_CATEGORIES.has(category)) notFound();

  if (state && !VALID_STATES.has(state)) notFound();

  const sub = cat.subcategories.find((s) => s.slug === subcategory);
  if (!sub) notFound();

  // Zero-query exit for valid slug triples that have no companies. This is the
  // change that lets the Neon compute reach its 300s autosuspend: ~2,700 of
  // these URLs exist, crawlers walk them, and each one used to cost up to five
  // aggregate queries across metadata and body before rendering the parent
  // category's listings under a subcategory heading.
  if (hasNoInventory(category, subcategory, state)) redirect(`/${category}/${state}`);

  const stateName = toTitleCase(state);

  // See generateMetadata: the count===0 parent retry is gone because the guard
  // above guarantees at least one company in this subcategory.
  const count = await countCompaniesByCategoryAndState(subcategory, state, {
    employeeRanges: activeEmployeeRanges,
  });
  const categoryToUse = subcategory;

  const [listing, stateCounts] = await Promise.all([
    stateListingSeo({ path: `/${category}/${subcategory}/${state}`, listSlug: categoryToUse, stateSlug: state, stateName, cat }),
    fetchStateCountsForCategory(categoryToUse),
  ]);
  const { companies: pageCompanies, seo } = listing;

  const subNoun = sub.titleNoun || producerNoun(sub.name);
  const pageTitle = `Top ${count} ${subNoun} in ${stateName} ${SEO_YEAR}`;
  const basePath       = `/${category}/${subcategory}/${state}`;

  const breadcrumbJsonLd = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home',            item: _BASE },
      { '@type': 'ListItem', position: 2, name: cat.shortName,     item: `${_BASE}/${category}` },
      { '@type': 'ListItem', position: 3, name: sub.name,          item: `${_BASE}/${category}/${subcategory}` },
      { '@type': 'ListItem', position: 4, name: stateName,         item: `${_BASE}/${category}/${subcategory}/${state}` },
    ],
  };

  const itemListJsonLd = {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    name: pageTitle,
    url: `${_BASE}${basePath}`,
    numberOfItems: pageCompanies.length,
    itemListElement: pageCompanies.map((company, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: company.name,
      url: `${_BASE}/company/${company.slug}`,
    })),
  };

  const filters = { basePath, activeStates: [], activeEmployeeRanges, stateCounts, showStateFilter: true, subcategories: cat?.subcategories, category, currentSubcategory: subcategory, currentState: state };

  return (
    <>
      <JsonLd data={breadcrumbJsonLd} />
      <JsonLd data={itemListJsonLd} />

      <div style={{ backgroundColor: '#ffffff', minHeight: '100vh' }}>

        {/* ── Page header ── */}
        <div style={{ backgroundColor: '#f8fafc', borderBottom: '1px solid #e2e8f0' }}>
          <div className="mx-auto max-w-[var(--max-width)] px-4 pt-6 pb-5 sm:px-6 sm:pt-10 sm:pb-9">

            {/* Breadcrumb */}
            <nav className="scrollbar-hide" style={{
              display: 'flex',
              alignItems: 'center',
              gap: 6,
              marginBottom: 20,
              flexWrap: 'nowrap',
              overflowX: 'auto',
              whiteSpace: 'nowrap',
              WebkitOverflowScrolling: 'touch',
            }}>
              <Link href="/" style={{ fontSize: 13, color: '#64748b', textDecoration: 'none', fontWeight: 500, flexShrink: 0 }}>Home</Link>
              <span style={{ color: '#cbd5e1', fontSize: 13, flexShrink: 0 }}>/</span>
              <Link href={`/${category}`} style={{ fontSize: 13, color: '#64748b', textDecoration: 'none', fontWeight: 500, flexShrink: 0 }}>{cat.shortName}</Link>
              <span style={{ color: '#cbd5e1', fontSize: 13, flexShrink: 0 }}>/</span>
              <span style={{ fontSize: 13, color: '#64748b', fontWeight: 500, flexShrink: 0 }}>{sub.name}</span>
              <span style={{ color: '#cbd5e1', fontSize: 13, flexShrink: 0 }}>/</span>
              <Link href={`/${category}/${state}`} style={{ fontSize: 13, color: '#64748b', textDecoration: 'none', fontWeight: 500, flexShrink: 0 }}>{cat.shortName} in {stateName}</Link>
            </nav>

            {/* Category badge */}
            <div style={{ display: 'inline-flex', alignItems: 'center', gap: 6, backgroundColor: cat.accent, borderRadius: 9999, padding: '4px 12px', marginBottom: 12 }}>
              <span style={{ fontSize: 11, fontWeight: 700, color: cat.accentText, letterSpacing: '0.08em', textTransform: 'uppercase' }}>{cat.shortName}</span>
            </div>

            <div style={{ display: 'flex', flexWrap: 'wrap', alignItems: 'center', justifyContent: 'space-between', gap: 20 }}>
              <div>
                <h1 style={{ fontSize: 'clamp(28px, 4vw, 44px)', fontWeight: 700, color: '#0f172a', letterSpacing: '-0.025em', lineHeight: 1.1, marginBottom: 10, marginTop: 0 }}>
                  {seo?.h1 || pageTitle}
                </h1>
                <LastUpdated date={listing.facts.lastUpdated} />
              </div>
              <div style={{
                display: 'inline-flex',
                alignItems: 'center',
                backgroundColor: '#f8fafc',
                border: '1px solid #e2e8f0',
                borderRadius: 9999,
                padding: '8px 16px',
                boxShadow: '0 1px 2px rgba(15, 23, 42, 0.05)',
                flexShrink: 0,
                height: 'fit-content'
              }}>
                <div style={{ display: 'flex', alignItems: 'baseline', gap: 6 }}>
                  <span style={{ fontSize: 15, fontWeight: 700, color: '#0f172a', fontVariantNumeric: 'tabular-nums', lineHeight: 1 }}>{count}</span>
                  <span style={{ fontSize: 13, color: '#64748b', fontWeight: 500, letterSpacing: '0.02em', lineHeight: 1 }}>listings</span>
                </div>
              </div>
            </div>

          </div>
        </div>

        {/* ── Content ── */}
        <div className="mx-auto max-w-[var(--max-width)] px-4 pt-5 pb-12 sm:px-6 sm:pt-8 sm:pb-16">
          <div className="lg:hidden">
            <Suspense fallback={null}><FilterBar {...filters} /></Suspense>
          </div>

          <div style={{ display: 'flex', flexDirection: 'row', gap: 28, marginTop: 24 }} className="listing-layout">

            {/* ── Company list ── */}
            <div style={{ flex: 1, minWidth: 0 }}>
              {seo?.intro.length > 0 && <SeoIntro paragraphs={seo.intro} />}
              <ComparisonTable companies={pageCompanies} caption={`Compare ${pageCompanies.length} ${subNoun.toLowerCase()} in ${stateName}`} />
              {count === 0 ? (
                <div style={{ textAlign: 'center', padding: '64px 24px', color: '#64748b' }}>
                  <p style={{ fontSize: 17, fontWeight: 600, color: '#0f172a', marginBottom: 8 }}>No listings yet</p>
                  <p style={{ fontSize: 14 }}>Be the first {sub.name} company in {stateName} to get listed.</p>
                  <Link href="/list-your-company" style={{ display: 'inline-flex', marginTop: 16, backgroundColor: '#0f172a', color: '#ffffff', fontSize: 13, fontWeight: 600, padding: '10px 20px', borderRadius: 8, textDecoration: 'none' }}>
                    List Your Company
                  </Link>
                </div>
              ) : (
                <div style={{ display: 'flex', flexDirection: 'column', gap: 10 }}>
                  {pageCompanies.map((company, i) => (
                    <CompanyCard
                      key={company.slug}
                      company={company}
                    />
                  ))}
                </div>
              )}
              {seo && <div style={{ marginTop: 32 }}><SeoFaqs faqs={seo.faqs} /></div>}
            </div>

            {/* ── Sidebar ── */}
            <aside style={{ width: 264, flexShrink: 0, display: 'flex', flexDirection: 'column', gap: 14 }} className="listing-sidebar lg:order-first">
              <div className="hidden lg:block">
                <Suspense fallback={null}><FilterBar {...filters} sidebar /></Suspense>
              </div>

              {/* Other subcategories */}
              <div style={{ backgroundColor: '#f8fafc', border: '1px solid #e2e8f0', borderRadius: 12, padding: 18 }}>
                <h3 style={{ fontSize: 12, fontWeight: 600, color: '#0f172a', marginBottom: 12, marginTop: 0, textTransform: 'uppercase', letterSpacing: '0.06em' }}>
                  {cat.shortName} in {stateName}
                </h3>
                <Link href={`/${category}/${state}`} className="sidebar-back-link" style={{ display: 'block', padding: '8px 10px', borderRadius: 8, fontSize: 13, textDecoration: 'none', color: '#64748b', marginBottom: 4, transition: 'background 0.1s' }}>
                  ← All {cat.shortName}
                </Link>
                <div style={{ display: 'flex', flexDirection: 'column', gap: 2 }}>
                  {cat.subcategories.map((s) => (
                    <Link
                      key={s.slug}
                      href={`/${category}/${s.slug}/${state}`}
                      style={{
                        display: 'block',
                        padding: '8px 10px',
                        borderRadius: 8,
                        fontSize: 13,
                        textDecoration: 'none',
                        transition: 'background 0.1s',
                        color: s.slug === subcategory ? '#0f172a' : '#475569',
                        backgroundColor: s.slug === subcategory ? '#ffffff' : 'transparent',
                        fontWeight: s.slug === subcategory ? 600 : 400,
                        border: s.slug === subcategory ? '1px solid #e2e8f0' : '1px solid transparent',
                      }}
                    >
                      {s.name}
                    </Link>
                  ))}
                </div>
              </div>

              {/* CTA */}
              <div style={{ background: 'linear-gradient(160deg, #0F172A, #070D18)', borderRadius: 12, padding: 20 }}>
                <Shield style={{ width: 22, height: 22, color: 'rgba(255,255,255,0.7)', marginBottom: 12 }} />
                <h3 style={{ fontSize: 14, fontWeight: 600, color: '#ffffff', marginBottom: 6, marginTop: 0 }}>List Your Company</h3>
                <p style={{ fontSize: 12, color: 'rgba(255,255,255,0.55)', lineHeight: 1.6, marginBottom: 14, marginTop: 0 }}>
                  Appear in ranked lists across all 50 states. Reach buyers actively searching.
                </p>
                <Link href="/list-your-company" className="cta-btn" style={{ display: 'block', textAlign: 'center', backgroundColor: '#F5A623', color: '#1A2E4A', fontWeight: 600, fontSize: 12, padding: '9px 16px', borderRadius: 8, textDecoration: 'none', transition: 'background 0.12s' }}>
                  Get Listed
                </Link>
              </div>
            </aside>
          </div>
        </div>
      </div>

      <style>{`
        @media (max-width: 1024px) {
          .listing-layout { flex-direction: column !important; }
          .listing-sidebar { width: 100% !important; }
        }
        .company-card:hover { border-color: #94a3b8 !important; box-shadow: 0 4px 16px -4px rgba(15,23,42,0.07) !important; }
        .sidebar-back-link:hover { background-color: #ffffff !important; color: #0f172a !important; }
        .cta-btn:hover { background-color: #D48E1A !important; }
      `}</style>
    </>
  );
}
