const PAGE_SIZE = 25;

const _BASE = (BASE_URL || 'https://www.firmsledger.com').replace(/\/$/, '');

const VALID_CATEGORIES = new Set(CATEGORY_SLUGS);
const VALID_STATES = new Set(ALL_US_STATES.map((s) => s.slug));

// Generated by scripts/build-static-data.mjs — every (category, subcategory,
// state) triple that has at least one approved company. Validating slugs was
// never the problem; validating INVENTORY is. Without this, the ~2,700 valid
// -but-empty triples each cost two aggregate queries to discover they were
// empty, and crawlers walking them kept the Neon compute from ever hitting its
// fixed 300s autosuspend. See HISTORY.md 2026-09-11.
const COMBO_KEYS = new Set(
  SUBCATEGORY_COMBOS.map((c) => `${c.category}|${c.sub}|${c.state}`)
);
// Prerender only what has real inventory. Matches MIN_LIVE_COMPANIES in
// app/sitemap.js, which already filters these URLs out of the sitemap below 5.
const PRERENDER_MIN = 5;

/**
 * True when this triple has no approved companies at all.
 *
 * Such a page used to render the PARENT category's companies via a count===0
 * fallback — a subcategory heading over unrelated listings, which is why the
 * sitemap already excluded them. We now redirect to the parent category+state
 * page instead: same content, honest URL, and zero queries to decide.
 *
 * NOT a 404: 29 of these URLs were earning Google impressions as of 2026-09-11
 * (235 impressions, three of them on page one), so 404ing them would throw away
 * real rankings. The redirect is temporary, not permanent, because a
 * subcategory can gain inventory later and get its page back.
 *
 * Falls open if the generated list is somehow empty — degrading to the old
 * query path beats redirecting the entire subcategory surface.
 */
function hasNoInventory(category, subcategory, state) {
  if (COMBO_KEYS.size === 0) return false;
  return !COMBO_KEYS.has(`${category}|${subcategory}|${state}`);
}

function toTitleCase(slug) {
  return slug.split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}

function buildFilterQueryString(activeEmployeeRanges, page) {
  const params = new URLSearchParams();
  if (activeEmployeeRanges.length) params.set('employees', activeEmployeeRanges.join(','));
  if (page > 1) params.set('page', String(page));
  const query = params.toString();
  return query ? `?${query}` : '';
}

function paginationRange(current, total) {
  const delta = 3;
  const range = [];
  const withDots = [];
  let prev;

  for (let i = 1; i <= total; i++) {
    if (i === 1 || i === total || (i >= current - delta && i <= current + delta)) {
      range.push(i);
    }
  }

  for (const i of range) {
    if (prev !== undefined) {
      if (i - prev === 2) withDots.push(prev + 1);
      else if (i - prev > 2) withDots.push('…');
    }
    withDots.push(i);
    prev = i;
  }

  return withDots;
}

// ─── Metadata ─────────────────────────────────────────────────────────────────

export async function generateMetadata({ params }) {
  const { category, state: subcategory, subcategory: state } = await params;
  // Page 1, unfiltered — reading searchParams would force the route dynamic.
  const sParams = {};
  const pageParam = undefined;

  if (
    VALID_STATES.has(category) &&
    VALID_CATEGORIES.has(subcategory) &&
    CATEGORY_MAP[subcategory]?.subcategories.some((s) => s.slug === state)
  ) {
    const query = new URLSearchParams(sParams).toString();
    const target = query ? `/${subcategory}/${state}/${category}?${query}` : `/${subcategory}/${state}/${category}`;
    permanentRedirect(target);
  }

  const cat = CATEGORY_MAP[category];
  if (!cat) return { title: 'Not Found' };

  if (state && !VALID_STATES.has(state)) return { title: 'Not Found' };

  const sub = cat.subcategories.find((s) => s.slug === subcategory);
  const subName  = sub?.name || toTitleCase(subcategory);
  const stateName = toTitleCase(state);

  // The page component redirects this case to /{category}/{state}. Return
  // placeholder metadata with zero queries rather than paying for a count we
  // are about to discard — this is half the saving.
  if (hasNoInventory(category, subcategory, state)) {
    return { title: subName, robots: { index: false, follow: true } };
  }

  // The count===0 parent-category retry that used to live here is gone: anything
  // reaching this line has at least one company in the subcategory itself, so
  // the fallback was unreachable and only doubled the cost of empty pages.
  const count = await countCompaniesByCategoryAndState(subcategory, state);
  const categoryToUse = subcategory;

  const totalPages    = Math.max(1, Math.ceil(count / PAGE_SIZE));
  const clampedPage   = Math.min(Math.max(1, parseInt(pageParam, 10) || 1), totalPages);
  
  const pageSuffix = clampedPage > 1 ? ` — Page ${clampedPage}` : '';
  const pageQuery = clampedPage > 1 ? `?page=${clampedPage}` : '';

  // Some subcategory slugs (e.g. wiring-harness) live under more than one parent category —
  // disambiguate the title with the parent name so the two URLs don't produce identical <title>s.
  const parentsWithSub = MANUFACTURING_CATEGORIES.filter((c) => c.subcategories.some((s) => s.slug === subcategory));
  const parentShortName = parentsWithSub.length > 1 ? (cat.shortName || cat.name) : null;

  const subNoun = sub?.titleNoun || producerNoun(subName);

  const title = clampedPage > 1
    ? buildListingTitle({ noun: subNoun, stateName, parentShortName, pageSuffix })
    : buildListingTitle({ count, noun: subNoun, stateName, parentShortName });

  const stats = await fetchCategoryStats(category, state);
  const description = `Find ${subName.toLowerCase()} manufacturers in ${stateName}. Part of the ${cat.name} directory. No paid placements.`;
  const canonical = `${_BASE}/${category}/${subcategory}/${state}${pageQuery}`;

  return {
    title: fitTitle(title),
    description,
    alternates: { canonical },
    robots: (clampedPage > 1 || count < 5) ? { index: false, follow: true } : { index: true, follow: true },
    openGraph: { images: [OG_IMAGE], title, description, type: 'website', url: canonical },
  };
}

export function generateStaticParams() {
  // CAREFUL: the folder names do not match the URL. The [state] segment
  // carries the SUBCATEGORY slug and [subcategory] carries the STATE slug —
  // see the destructuring in generateMetadata and the page component. Swapping
  // these silently generates thousands of wrong pages.
  return SUBCATEGORY_COMBOS
    .filter((c) => c.n >= PRERENDER_MIN)
    .map((c) => ({ category: c.category, state: c.sub, subcategory: c.state }));
}



